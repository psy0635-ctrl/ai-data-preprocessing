
# 1. 필요한 라이브러리 불러오기

# 숫자 계산과 배열을 쉽게 사용하기 위한 라이브러리
import numpy as np

# 인공신경망 학습을 위한 TensorFlow
import tensorflow as tf

# TensorFlow 안의 Keras 기능 사용
from tensorflow import keras

# 신경망 입력층을 만들 때 사용
from keras import Input

# 신경망 모델을 만들 때 사용
from keras.models import Model

# 뉴런으로 이루어진 Dense 층을 만들 때 사용
from keras.layers import Dense

# 그래프를 그리기 위한 라이브러리
import matplotlib.pyplot as plt


# 2. AI가 학습해야 할 '정답 시스템' 만들기

def test_system(x):

    # x값에 따라 y값을 계산하는 함수
    return 0.01 * x * x + 2.0

    # return 0.4 * x + 8.0


# 3. 인공신경망 모델 생성 함수

def get_model():

    # 난수 발생 기준을 고정
    # 신경망의 초기 가중치는 랜덤하게 만들어지므로
    # 가능한 한 비슷한 조건에서 실험하기 위해 사용
    # tf.random.set_seed(1000)


    # --------------------------------------------------------
    # 입력층 Input
    # --------------------------------------------------------

    # 입력값 x는 숫자 1개이므로 shape=(1,)
    #
    # 예:
    # x = -50
    # x = 0
    # x = 30
    #
    input = tf.keras.Input(
        shape=(1,),
        name="Input"
    )


    # --------------------------------------------------------
    # 은닉층 Hidden
    # --------------------------------------------------------

    # Dense(2)
    # → 은닉층의 뉴런을 2개 만든다는 뜻
    #
    # activation='tanh'
    # → 각 뉴런의 계산 결과에 tanh 활성화 함수를 적용
    #
    # 각 뉴런은 대략:
    #
    # W*x + b
    #    ↓
    # tanh()
    #
    # 과정을 거침
    #
    # tanh의 출력 범위는 약 -1 ~ 1
    #
    # 이런 비선형 활성화 함수 덕분에
    # 단순한 직선이 아닌 곡선도 표현할 수 있게 됨
    hidden = Dense(
        2,
        activation='tanh',
        name="Hidden"
    )(input)


    # --------------------------------------------------------
    # 출력층 Output
    # --------------------------------------------------------

    # 출력값 y는 숫자 하나이므로 Dense(1)
    #
    # activation='linear'
    # → 계산한 값을 그대로 출력
    #
    # Hidden 뉴런 2개의 결과를 받아
    # 최종 y값을 계산함
    output = Dense(
        1,
        activation='linear',
        name="Output"
    )(hidden)


    # --------------------------------------------------------
    # Input과 Output을 연결해서 하나의 모델 생성
    # --------------------------------------------------------

    # 구조:
    #
    # Input
    #   ↓
    # Hidden (뉴런 2개, tanh)
    #   ↓
    # Output (뉴런 1개, linear)
    #
    model = tf.keras.Model(
        inputs=[input],
        outputs=[output]
    )


    # --------------------------------------------------------
    # Optimizer 설정
    # --------------------------------------------------------

    # Adam:
    # 예측값과 실제값의 오차를 줄이기 위해
    # 가중치(W)와 바이어스(b)를 수정하는 알고리즘
    #
    # learning_rate=0.0025
    # → 한 번 수정할 때 얼마나 크게 움직일지 결정
    opt = keras.optimizers.Adam(
        learning_rate=0.0025
    )


    # --------------------------------------------------------
    # 학습 방법 설정
    # --------------------------------------------------------

    model.compile(

        # MSE = Mean Squared Error
        # 실제값과 예측값의 차이를 제곱해서 평균
        #
        # 작을수록 학습이 잘 된 것
        loss='mse',

        # W와 b를 수정할 방법으로 Adam 사용
        optimizer=opt,

        # 학습 과정에서 같이 확인할 평가값
        # mse = 평균 제곱 오차
        # mae = 평균 절대 오차
        metrics=['mse', 'mae']
    )


    # 만들어진 신경망 구조 출력
    #
    # 예상 구조:
    #
    # Input     → parameter 0
    # Hidden    → parameter 4
    # Output    → parameter 3
    #
    # 총 7개의 학습 가능한 파라미터
    model.summary()


    # 만들어진 모델을 밖으로 반환
    return model


# ============================================================
# 4. 프로그램을 직접 실행했을 때 시작되는 부분
# ============================================================

if __name__ == '__main__':


    # --------------------------------------------------------
    # 4-1. 학습용 x 데이터 만들기
    # --------------------------------------------------------

    # -50부터 50까지 10씩 증가
    #
    # 결과:
    #
    # [-50, -40, -30, -20, -10,
    #    0,
    #   10,  20,  30,  40,  50]
    #
    x_datas = np.array(
        range(-50, 51, 10)
    )


    # --------------------------------------------------------
    # 4-2. 학습용 정답 y 데이터를 저장할 빈 리스트
    # --------------------------------------------------------

    y_datas = []


    # --------------------------------------------------------
    # 4-3. 각각의 x에 대한 정답 y 계산
    # --------------------------------------------------------

    for x in x_datas:

        # test_system(x)를 이용해서
        #
        # y = 0.01*x*x + 2
        #
        # 정답을 계산하고 y_datas에 추가
        y_datas.append(
            test_system(x)
        )


    # Python 리스트를 NumPy 배열로 변경
    y_datas = np.array(y_datas)


    # --------------------------------------------------------
    # 학습 데이터를 그래프로 확인하고 싶을 때 사용
    # --------------------------------------------------------

    # 현재는 #으로 주석 처리되어 있으므로 실행되지 않음
    #
    # 실행하면 U자 모양의 점들이 나타남
    #
    # plt.scatter(x_datas, y_datas)
    # plt.show()


    # ========================================================
    # 5. 신경망 모델 생성
    # ========================================================

    model = get_model()


    # ========================================================
    # 6. 신경망 학습
    # ========================================================

    # x_datas = 문제
    # y_datas = 정답
    #
    # epochs=20000
    # → 전체 학습 데이터를 20,000번 반복해서 공부
    #
    # shuffle=True
    # → 매 학습 시 데이터 순서를 섞음
    #
    # history에는 학습 과정의 loss, mse, mae 등이 저장됨
    history = model.fit(
        x_datas,
        y_datas,
        epochs=20000,
        shuffle=True
    )


    # ========================================================
    # 7. Loss 그래프 출력
    # ========================================================

    # 학습 횟수가 증가하면서
    # loss가 어떻게 변하는지 그래프로 그림
    #
    # 정상적으로 학습된다면
    # 전체적으로 loss가 감소하는 모습을 볼 수 있음
    plt.plot(
        history.history['loss'],
        'b',
        label='loss'
    )

    plt.show()


    # ========================================================
    # 8. 새로운 테스트 데이터 준비
    # ========================================================

    # 학습할 때 사용하지 않았던 값으로 테스트
    #
    # 학습:
    # -50, -40, -30 ...
    #
    # 테스트:
    # -45, -35, -25 ...
    #
    x_test = np.array(
        range(-45, 45, 10)
    )


    # ========================================================
    # 9. 학습된 AI에게 새로운 x값을 예측하게 함
    # ========================================================

    result = model.predict(x_test)


    # ========================================================
    # 10. 실제 학습 데이터와 AI 예측 결과 비교
    # ========================================================

    # 파란 점:
    # 우리가 알고 있는 실제 정답
    plt.scatter(
        x_datas,
        y_datas,
        c='blue',
        s=5
    )


    # 빨간 점:
    # 인공신경망이 예측한 결과
    plt.scatter(
        x_test,
        result,
        c='red',
        s=5
    )


    # 그래프 출력
    #
    # 학습이 잘 됐다면
    # 빨간 점들이 파란 점들이 만드는
    # U자 곡선 사이에 자연스럽게 위치해야 함
    plt.show()


    # ========================================================
    # 11. 학습된 가중치와 바이어스 확인
    # ========================================================

    weights = model.get_weights()


    # 주의:
    #
    # 이번 모델은 이전 모델처럼 W 하나, b 하나만 있는 것이 아님
    #
    # weights[0] = Input → Hidden의 가중치 2개
    # weights[1] = Hidden의 바이어스 2개
    # weights[2] = Hidden → Output의 가중치 2개
    # weights[3] = Output의 바이어스 1개


    print("Hidden W :", weights[0])
    print("Hidden b :", weights[1])

    print("Output W :", weights[2])
    print("Output b :", weights[3])